def call(dry: bool, activate: bool = False):
    body = {
        "loan_tokens": ANCHOR,
        "domain_tokens": ANCHOR,      # 동일 리스트 → keep = 앵커 1개 이상 포함
        "exclude_tokens": EXCLUDE,
        "dry_run": dry,
        "activate": activate,
        "max_pause": 200000,
    }
    r = requests.post(BASE + EP, json=body, timeout=900)
    print('HTTP', r.status_code)
    try:
        d = r.json()
    except Exception:
        print(r.text[:500])
        return None
    for k, v in d.items():
        if k != 'samples':
            print(f'  {k}: {v}')
    if d.get('samples'):
        print('  samples:', d['samples'][:30])
    return d


