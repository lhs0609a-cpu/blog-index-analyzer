def regions():
    src = open(os.path.join(HERE, "dovision_seed_gen_200k.py"), encoding="utf-8").read()
    i = src.index("REGIONS = []")
    ns = {}
    exec(src[:i] + src[i:src.index("\n\n", i)], ns)
    return ns["REGIONS"]


def main():
    seeds = set()
    for b in BASE:
        for t in INTENT:
            seeds.add(b + t)
    for b in BRANDS:
        for t in BRAND_INTENT:
            seeds.add(b + t)
    R = regions()
    for r in R:
        for t in REGION_INTENT:
            seeds.add(r + t)
    for e in EXPO:
        for m in EXPO_MOD:
            seeds.add(e + m if m else e)
            if m:
                seeds.add(m + e)
    seeds = sorted(s for s in seeds if 3 <= len(s) <= 20)
    json.dump(seeds, open(OUT, "w", encoding="utf-8"), ensure_ascii=False)
    print(f"업종 {len(BASE)}×의도 {len(INTENT)} + 브랜드 {len(BRANDS)}×{len(BRAND_INTENT)} "
          f"+ 지역 {len(R)}×{len(REGION_INTENT)} + 박람회")
    print(f"→ 조합 씨앗 {len(seeds):,}개  {OUT}")


if __name__ == "__main__":
    main()
