def _generic_ok(k: str) -> bool:
    if not any(h in k for h in _G_HEAD):
        return False
    rest = k
    for t in sorted(_G_HEAD + _G_MOD, key=len, reverse=True):
        rest = rest.replace(t, "")
    return len(rest) <= 1

