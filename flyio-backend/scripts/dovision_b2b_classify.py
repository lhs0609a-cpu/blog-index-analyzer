def classify(kw: str):
    k = kw.lower().replace(" ", "")
    if OFF_RE.search(k):
        return None, "off"
    if not any(t in k for t in BIZ):
        return None, "no_biz"
    has_edu = any(t in k for t in EDU)
    has_mom = any(t in k for t in MOM)
    if not (has_edu or has_mom):
        return None, "no_anchor"
    for axis, toks in AXIS_RULES:
        if any(t in k for t in toks):
            # 교육 앵커 없는 '교육창업' 매칭은 있을 수 없으나 방어적으로
            return axis, ("edu" if has_edu else "mom")
    return None, "no_axis"

