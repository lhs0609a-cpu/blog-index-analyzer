def rescore(kw):
    k = kw.replace(" ", "")
    for r in DROP_RE:
        m = r.search(k)
        if m:
            return None, "cut:" + m.group(0), None, None
    if CORE45.search(k):
        fit, fitname = 45, "핵심업종"
    elif EDU40.search(k):
        fit, fitname = 40, "교육업종"
    elif BRAND.search(k):
        fit, fitname = 35, "경쟁브랜드"
    elif EDU20.search(k):
        fit, fitname = 20, "교육일반"
    else:
        fit, fitname = 5, "업종미정"
    stage, stagename = 8, "탐색"
    for s, r in STAGE:
        if r.search(k):
            stage = s
            stagename = {45: "가맹접촉", 40: "창업실행", 38: "인수·매물", 35: "인허가·등록",
                         30: "돈계산", 28: "브랜드검토", 25: "원장실무", 22: "원생모집",
                         26: "전환·컨설팅", 18: "폐업·정리", 15: "박람회"}[s]
            break
    sc = fit + stage
    for b, r in BONUS:
        if r.search(k):
            sc += b
    for p, r in MALUS:
        if r.search(k):
            sc += p
    return max(0, min(100, sc)), fitname, stagename, fit


def main():
    rows = list(csv.DictReader(io.open(HERE + "/dovision_fc_final.csv", encoding="utf-8-sig")))
    bids = {r["keyword"]: r for r in
            csv.DictReader(io.open(HERE + "/dovision_fc_bids.csv", encoding="utf-8-sig"))}
    out, cut = [], []
    for r in rows:
        sc, fit, stage, _ = rescore(r["keyword"])
        if sc is None:
            cut.append((r["keyword"], fit))
            continue
        b = bids.get(r["keyword"], {})
        out.append({
            "keyword": r["keyword"], "vol": int(r["monthly_total"]),
            "score": sc, "fit": fit, "stage": stage, "axis": r["axis"],
            "bid5": int(b["bid_5"]) if b.get("bid_5") else "",
            "bid1": int(b["bid_1"]) if b.get("bid_1") else "",
            "source": r["source"],
        })
    out.sort(key=lambda r: (-r["score"], -r["vol"], r["keyword"]))
    print(f"원장 {len(rows)} → 컷 {len(cut)} → 남은 {len(out)}")
    return out, cut


if __name__ == "__main__":
    out, cut = main()
    if "--cut" in sys.argv:
        for k, why in cut[:400]:
            print(k, why)
    else:
        for i, r in enumerate(out[:60], 1):
            print(f"{i:3} {r['score']:3} {r['vol']:>6} {r['fit']}/{r['stage']:8} {r['keyword']}")
