def main():
    live_all = []
    for label, kws in AXES.items():
        got = {}
        uniq = [k.replace(" ", "") for k in kws]
        for i in range(0, len(uniq), 5):
            for r in keywordstool(uniq[i:i + 5]):
                got[r["kw"]] = r["total"]
            time.sleep(0.05)
        live = sorted(((got.get(k, 0), k) for k in set(uniq) if got.get(k, 0) >= 10), reverse=True)
        dead = [k for k in uniq if got.get(k, 0) < 10]
        tot = sum(v for v, _ in live)
        print(f"\n{label}  — 산 것 {len(live)}/{len(uniq)} / 월검색합 {tot:,}")
        if live:
            print("   " + ", ".join(f"{k}({v:,})" for v, k in live))
        if dead:
            print("   [0] " + ", ".join(dead[:18]) + (" …" if len(dead) > 18 else ""))
        live_all += [(v, k, label) for v, k in live]
    print(f"\n=== 3차 축 합계: {len(live_all)}개 / 월 {sum(v for v,_,_ in live_all):,} ===")


if __name__ == "__main__":
    main()
