def classify(kw: str):
    """(축, 사유) 반환. 축이 None 이면 오프도메인."""
    k = (kw or "").replace(" ", "").lower()
    if not k or len(k) < 2:
        return None, "too_short"
    if len(k) >= 22:
        return None, "too_long"          # GPT 패딩성 문자열
    if OFF_RE.search(k):
        return None, "off:" + OFF_RE.search(k).group(0)
    for _c in CONTEXT_RE:
        m = _c.search(k)
        if m:
            return None, "ctx:" + m.group(0)
    for _b in AMBIG_BRAND:
        if _b in k and not any(e in k for e in EDU_CTX):
            return None, "ambig:" + _b
    # 두비전 본질 토큰(STRONG)이 있어야 우리 고객이다. CORE 만 맞은 교육 일반어
    # ('초등영어', '목동수학학원')은 여기서 죽는다 — 우리가 파는 게 그게 아니다.
    if not STRONG_RE.search(k):
        return None, "weak_only" if CORE_RE.search(k) else "no_core"
    for axis, toks in AXIS_RULES:
        if toks and any(t in k for t in toks):
            # 지역어가 붙어 있으면 지역 축이 내방 의도로 더 강하다
            if REGION_RE.search(k) and any(
                    t in k for t in ("학원", "클리닉", "센터", "교습소", "공부방", "과외")):
                return "지역×학습", axis
            return axis, "tok"
    if REGION_RE.search(k) and KID_RE.search(k):
        return "지역×학습", "region+kid"
    # STRONG 은 맞았는데 축 토큰이 없는 말 — 고민의 입구가 되는 넓은 말이라 살린다.
    if KID_RE.search(k) or STRONG_RE.search(k):
        return "학습일반", "strong"
    return None, "no_axis"


def ondomain(kw, total):
    return total >= MIN_VOL and classify(kw)[0] is not None


