const norm=s=>s.replace(/[\s·\-_,\.]/g,'');
// 지역어는 '접두'에서만 제거한다. (중간 제거 시 '유사천포창'→'유포창' 같은 파괴가 생김)
// 행정접미(동/구/역…)는 지역어 바로 뒤에 붙었을 때만 뗀다. 단독 선두 제거 금지
// — 그래야 '가려움증'의 '가', '구순염'의 '구', '면역력'의 '면'이 살아남는다.
const BIZ_S=[...BIZ].sort((x,y)=>y.length-x.length);
const REG_S=[...REGION].sort((x,y)=>y.length-x.length);
const rmBiz=s=>{let ch=true;while(ch){ch=false;for(const t of BIZ_S)if(s.includes(t)){s=s.split(t).join('');ch=true;}}return s;};
// useSuf=false: 지역어만 접두 제거   useSuf=true: 지역어 + 뒤따르는 행정접미 1자까지 제거
const rmReg=(s,useSuf)=>{let ch=true;
  while(ch){ch=false;
    for(const t of REG_S){ if(s.startsWith(t)){ s=s.slice(t.length);
      if(useSuf) for(const f of SUF){ if(s.startsWith(f)){ s=s.slice(f.length); break; } }
      ch=true; break; } }
  }
  return s;};
// 접미까지 떼면 빈 문자열 = 순수 '지역+업종'.
// 그렇지 않으면 접미를 떼지 않은 쪽을 잔여어로 쓴다
// ('서초면역력한의원'→'면역력'(O) / '역력'(X), '강남구내염한의원'→'구내염'(O) / '내염'(X)).
const strip=kw=>{
  const base=rmBiz(norm(kw));
  const loose=rmReg(base,true);
  return loose===''?'':rmReg(base,false);
};
// 브랜드는 보호
const BRAND=/소잠/;
const isBare=kw=>!BRAND.test(kw)&&/한의원|한방|병원|의원|클리닉|한약국/.test(norm(kw))&&strip(kw)==='';
module.exports={strip,isBare,BIZ,REGION,SUF};
