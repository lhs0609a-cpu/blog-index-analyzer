def GARBAGE(t):
    for f in _FIN:
        if f in t:
            return f"기계조합:{f}"
    if len(t) >= 14:
        for tok in ["비타민", "영양소", "상담", "센터", "비용", "전문", "성장", "클리닉"]:
            if t.count(tok) >= 2:
                return f"토큰중복:{tok}"
    if len(t) >= 20:
        return "과장문자열"
    for b in _BOILER:
        if b in t and len(t) >= 14:
            return f"상용구:{b}"
    if len(t) <= 1 and t not in BROAD_SET:
        return "단문자"
    return None


def classify(kw):
    t = N(kw)
    if not hit(t, KEEP_FIRST) and (w := hit(t, TRAP)):
        return "OFF", w
    if (w := hit(t, HARD_OFF)):
        return "OFF", w
    if (w := hit(t, ADULT_OBESITY)) and not (hit(t, AUD) or AUD_RE.search(t)):
        return "ADULT", w
    if (w := hit(t, NEG_PROFILE)):
        return "NEG", w
    if (w := GARBAGE(t)):
        return "JUNK", w
    if (w := hit(t, SUPP)):
        return "SUPP", w
    if (w := hit(t, INFO_TAIL)):
        return "INFO", w
    if t in BROAD_SET:
        return "BROAD", "단독광범위어"
    if (w := hit(t, STRONG)):
        return "KEEP", w
    if HEIGHT_CTX.search(t):
        return "KEEP", "키성장문맥"
    if t.startswith("키") and len(t) >= 3:   # TRAP·HARD_OFF 통과분이라 '키'=신장 확정
        return "KEEP", "키접두"
    if (w := hit(t, BORDER_DEF["SPORT"])):
        return "SPORT", w
    if (w := hit(t, BORDER_DEF["CARE"])):
        return "CARE", w
    tw = t.replace("키즈", "").replace("키트", "")
    w = hit(tw, WEAK)
    if w and (hit(t, AUD) or AUD_RE.search(t)):
        return "KEEP", w
    return "OFF", (w or "-")


