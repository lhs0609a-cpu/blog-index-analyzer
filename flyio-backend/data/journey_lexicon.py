def _norm(text: str) -> str:
    return (text or "").strip().lower().replace(" ", "")


def _hit(keyword: str, token: str, collisions: Dict[str, List[str]]) -> bool:
    """토큰이 키워드에 살아있는가. 충돌 목록을 반드시 통과해야 인정."""
    if not token or token not in keyword:
        return False
    for bad in collisions.get(token, ()):
        if bad in keyword:
            return False
    return True


def _match_any(keyword: str, tokens: Sequence[str],
               collisions: Dict[str, List[str]]) -> Optional[str]:
    for t in tokens:
        if _hit(keyword, _norm(t), collisions):
            return t
    return None


def match_region(keyword_raw: str) -> Optional[str]:
    """지역 토큰 매칭. 충돌목록 + **위치 규칙**을 함께 건다.

    위치 규칙: 지역명은 키워드 맨 앞이거나 띄어쓰기 직후에만 온다.
        "강남 여드름" ✓   "분당여드름피부과" ✓   "여드름 강남" ✓
        "물광주사"    ✗   ← 물[광주]사. 충돌목록에만 의존하면 이런 게 계속 샌다.

    충돌목록은 사후 대응이고 이 규칙이 사전 예방이다. 둘 다 건다.
    """
    segments = [s for s in (keyword_raw or "").strip().lower().split() if s]
    for seg in segments:
        for region in REGION_TOKENS:
            r = _norm(region)
            if not seg.startswith(r):
                continue
            if any(bad in _norm(keyword_raw) for bad in REGION_COLLISIONS.get(region, ())):
                continue
            return region
    return None


def make_adhoc_spec(business_seeds: Sequence[str], label: str = "") -> Dict:
    """사전이 없는 업종을 위한 즉석 사전.

    자영업 업종은 수백 개고 사람이 사전을 다 만들 수 없다.
    그래서 **업장이 직접 적은 몇 단어**를 anchor 로 쓰고, trap 은 공통 것만 건다.

    한계는 정직하게: 손으로 만든 사전보다 반드시 나쁘다.
      - anchor 가 얇아 수집량의 대부분이 걸러진다(통과율 하락)
      - 업종 고유 오염(그 업종에만 있는 제품·자격증 수요)을 못 막는다
    그 구멍은 SERP 판정이 메운다 — 검색 결과 상단이 쇼핑이면 그건 팔 대상이 아니다.
    """
    seeds = [s.strip() for s in business_seeds if s and s.strip()]
    return {
        "label": label or f"무사전: {', '.join(seeds[:4])}",
        "adhoc": True,
        "demand_shape": None,            # 선언하지 않는다 — 실측이 정한다
        "condition": [],
        "treatment": seeds,              # 단독 검색은 '해결책 인지'로 본다
        "brand": [],
        "trap": [],                      # 공통 trap 만 적용
        "stage_hint": {},
    }


def is_on_domain(keyword: str, industry: str, spec: Optional[Dict] = None) -> Tuple[bool, str]:
    """업종 도메인 안의 키워드인가. (anchor 하나 이상 AND trap 없음)"""
    if spec is None:
        spec = INDUSTRY.get(industry)
    if not spec:
        raise KeyError(f"unknown industry: {industry}")
    kw = _norm(keyword)

    common = _match_any(kw, COMMON_TRAP, {})
    if common:
        return False, f"trap:{common}"

    trap = _match_any(kw, spec.get("trap", []), {})
    if trap:
        return False, f"trap:{trap}"

    anchors = (spec.get("condition", []) + spec.get("treatment", [])
               + spec.get("brand", []))
    hit = _match_any(kw, anchors, COLLISIONS)
    if not hit:
        return False, "no_anchor"
    return True, f"anchor:{hit}"


def classify_stage(keyword: str, industry: str, spec: Optional[Dict] = None) -> Dict:
    """키워드 → 여정 단계.

    Returns: {stage, confidence, matched, basis}
        stage=0 은 미분류(anchor 는 있으나 의도어가 없고 단독 판정도 불가).
    """
    if spec is None:
        spec = INDUSTRY[industry]
    kw = _norm(keyword)

    hits: List[Tuple[int, str, str]] = []   # (stage, matched, basis)

    # 1) 업종 고유 힌트 — 공통 사전보다 우선
    for token, stage in spec.get("stage_hint", {}).items():
        if _hit(kw, _norm(token), COLLISIONS):
            hits.append((stage, token, "hint"))

    # 2) 지역 → 5단계(행동). 공백이 살아있는 원문을 넘긴다(위치 규칙에 필요).
    region = match_region(keyword)
    if region:
        hits.append((5, region, "region"))

    # 3) 브랜드 + 지역이 아닌 단독 브랜드는 아래 4)에서 처리. 브랜드+예약류는 slot 으로.
    brand = _match_any(kw, spec.get("brand", []), COLLISIONS)

    # 4) 공통 의도어
    for stage, rules in STAGE_LEXICON.items():
        for suf in rules.get("suffix", []):
            if kw.endswith(_norm(suf)):
                hits.append((stage, suf, "suffix"))
                break
        tok = _match_any(kw, rules.get("token", []), COLLISIONS)
        if tok:
            hits.append((stage, tok, "token"))

    if hits:
        # bottom-most wins — 구매에 가장 가까운 신호를 택한다
        stage, matched, basis = max(hits, key=lambda h: h[0])
        conf = 0.9 if basis in ("hint", "region", "suffix") else 0.8
        if len(hits) > 1:
            conf = min(0.95, conf + 0.05)
        return {"stage": stage, "confidence": conf, "matched": matched,
                "basis": basis, "all_hits": hits}

    # 5) 의도어가 없다 → 단독 대상어의 성격으로 배정.
    #    treatment 를 먼저 본다: 증상어와 시술어가 같이 있으면("여드름 프락셀")
    #    이미 해결책 단계로 넘어간 사람이다.
    if brand or _match_any(kw, spec.get("treatment", []), COLLISIONS):
        return {"stage": 2, "confidence": 0.5, "matched": "", "basis": "bare_treatment"}
    if _match_any(kw, spec.get("condition", []), COLLISIONS):
        return {"stage": 1, "confidence": 0.5, "matched": "", "basis": "bare_condition"}

    return {"stage": 0, "confidence": 0.0, "matched": "", "basis": "unclassified"}


def audit_lexicon(industry: str) -> List[str]:
    """사전 자체의 위생 점검. 2글자 anchor·중복·자기충돌을 잡는다."""
    spec = INDUSTRY[industry]
    problems: List[str] = []

    anchors = spec.get("condition", []) + spec.get("treatment", []) + spec.get("brand", [])
    for a in anchors:
        if len(a) <= 2 and a not in SHORT_ANCHOR_OK:
            problems.append(f"2글자 anchor '{a}' — 인명/지역광고 유입 위험. SHORT_ANCHOR_OK 등재 필요")

    # brand 는 treatment 와 겹치는 게 정상(포텐자는 브랜드이자 시술).
    # 같은 범주 안에서의 중복만 문제로 본다.
    for cat in ("condition", "treatment", "brand"):
        seen = set()
        for a in spec.get(cat, []):
            if a in seen:
                problems.append(f"anchor 중복({cat}): '{a}'")
            seen.add(a)
    overlap = set(spec.get("condition", [])) & set(spec.get("treatment", []))
    for a in sorted(overlap):
        problems.append(f"범주 충돌: '{a}' 가 condition·treatment 양쪽에 있음 "
                        f"— 단독 검색 시 단계가 뒤집힘")

    # anchor 가 trap 에 잡아먹히는 자기충돌
    for a in anchors:
        for t in spec.get("trap", []):
            if _norm(t) in _norm(a):
                problems.append(f"자기충돌: anchor '{a}' 가 trap '{t}' 에 걸림 — 영원히 제외됨")

    return problems
