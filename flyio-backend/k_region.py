_A_MAP = {t: k for k, v in A_REGIONS.items() for t in v}
_B_MAP = {t: k for k, v in B_REGIONS.items() for t in v}
_ALL = [(t, "A", _A_MAP[t]) for t in _A_MAP] + [(t, "B", _B_MAP[t]) for t in _B_MAP]
# 긴 토큰 우선 (세종시 > 세종)
_ALL.sort(key=lambda x: -len(x[0]))
_RE = [(re.compile(f"^{re.escape(t)}{_SUF}"), re.compile(f"{re.escape(t)}{_SUF}$"), t, g, a)
       for t, g, a in _ALL]


def region_grade(kw: str):
    """(등급, 권역, 매칭토큰) — 'A' | 'B' | None. 지역명은 앞/뒤 끝에서만 인정."""
    t = (kw or "").replace(" ", "")
    for tr in REGION_TRAP:
        if tr in t:
            return (None, None, None)
    for b in BRANCH:
        if b in t:
            return (None, None, None)
    if not DOMAIN_TAIL.search(t):
        return (None, None, None)
    for pre, suf, tok, g, area in _RE:
        m = pre.match(t)
        if m and len(t) - m.end() >= 2:          # 지역명만 남는 것 방지
            return (g, area, tok)
        m = suf.search(t)
        if m and m.start() >= 2:
            return (g, area, tok)
    return (None, None, None)
