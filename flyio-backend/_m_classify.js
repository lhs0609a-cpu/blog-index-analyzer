const FIN=['대출','론','자금','담보','신용','마이너스통장','마통','금리','이자','대환','리스','캐피탈','저축은행','금융','한도','상환','연체','파산','회생','융자','보증','창업','운영자금','시설자금','인수','개설','투자','펀딩','핀테크','비상금','빚','채무','상환','조건','한도조회','금리비교','은행'];
// 오탐 유발: '론'은 '이론/에어컨론' 등, '외과'는 '외과'만, '인수'는 '인수인계' 등
const BAD=[/리스트/,/공론/,/양심/,/승계/,/신고서류/,/이론/,/론칭/,/살롱/,/클론/,/사이클론/,/멜론/,/아론/,/텔레론/,/론리/,/인수인계/,/인수위/,/보건소장/];
function subjHit(k){return SUBJ.filter(s=>k.includes(s))}
function finHit(k){
  const out=[];
  for(const f of FIN){
    if(f==='론'){ if(/[가-힣A-Za-z]론(?![가-힣])/.test(k)&&!BAD.some(r=>r.test(k)))out.push(f); continue; }
    if(k.includes(f))out.push(f);
  }
  return out;
}
function classify(k){
  if(BAD.some(r=>r.test(k)))return null;
  const s=subjHit(k),f=finHit(k);
  if(!s.length||!f.length)return null;
  return {subj:s,fin:f};
}
module.exports={classify,subjHit,finHit};
