// 해울 '내원' 판정기 v2 — 검색량이 아니라 '실재 증거'로 거른다.
// 1) 진료축 안 → 2) 자가치료·약탐색·정보성 제외 → 3) 내원 신호 등급
module.exports=(function(){
const norm=s=>String(s).replace(/\s+/g,'').toLowerCase();
const AXIS=/(두통|편두통|삼차신경통|후두신경통|뇌압|뒷골|두중감|어지럼|어지러|현훈|이석증|메니에르|전정신경|평형장애|비틀거|휘청|자율신경|기립성|미주신경|실신|공황|불면|잠못|수면장애|머리아프|머리아플|머리아파|머리아픔|머리통증|머리지끈|머리띵|머리무거|머리조임|머리찌릿|관자놀이통|정수리통|이마통|미간통|뒤통수통|두피통|뒷목통|목뒤통|후두부통)/;
const JUNK=/(실업급여|산재|장애등급|보험금|노래|가사|드라마|영화|웹툰|소설|게임|주식|부동산|대출|보험료청구|자동차|강아지|고양이|맛집|레시피|생오리|국밥|여드름|필러|보톡스시술|리프팅|눈썹|주름|미용|영어로|한자|일본어|중국어|사자성어|뜻이|뜻은|의뜻|퀴즈|디시|더쿠|블라인드|군대|면제|사망|보험금)/;
const OTHER=/(천안|제주|원주|김포|평택|부산|대구|광주|대전|울산|인천|청주|전주|창원|포항|구미|안동|여수|목포|춘천|강릉|세종|김해|양산|진주|순천|익산|군산|경주|거제|통영|아산|당진|서산|충주|제천|속초|동해|삼척|영주|상주|문경|밀양|사천|나주|광양|정읍|남원|김천|영천|공주|보령|논산|서귀포|일산|파주|의정부|남양주|구리|수원|성남|분당|용인|안양|부천|시흥|안산|화성|평촌|광명|하남|양주|포천|동두천|대연동|명동|범계|언주|송도|서면|동탄|광교|청라|영통|죽전|기흥|동래|해운대|사상|연산동|덕천|화명|수지|구성|영통|병점|오산|안성|이천|여주|양평|가평|강화|계양|부평|주안|논현동|간석|만수)/;
// 양방실패는 '약' 이 들어가도 내원 신호다 — 약탐색 컷보다 먼저 통과시킨다(순서 함정).
const FAIL=/(약부작용|약의부작용|부작용|약안듣|약이안듣|약먹어도|약을먹어도|먹어도|약효과없|효과없|내성|의존|끊는법|끊고싶|검사정상|이상없|정상인데|검사했는데|검사해도|신경과갔|병원갔는데|안낫|낫지않|안나아|재발|만성화)/;
// 자가처치·제품탐색 — 내원이 아니다
const SELF=/(자가치료|자가교정|자가운동|자가|스스로|집에서|운동법|운동방법|스트레칭|체조|마사지|지압|자세교정|베개|음식|먹는것|좋은음식|과일|영양제|비타민|효능|차효능|한방차|민간요법|완화법|푸는법|해소법)/;
const DRUG=/(약추천|약이름|약종류|약국|진통제추천|타이레놀|게보린|펜잘|이지엔|아스피린|낙센|처방전|약값|약국에서|무슨약|어떤약|약비교|약순위)/;
const CLINIC=/(한의원|한방병원|병원|의원(?!리|인)|클리닉|치료센터|상담센터|명의|전문의|전문병원|전문의원|잘하는곳|잘보는곳|잘보는|유명한|어디로|어디가|어디서|어느병원|어느과|무슨과|어떤과|진료과|과추천|병원추천|추천병원|진료받|진찰|내원|초진)/;
const DECIDE=/(비용|가격|얼마|실비|보험적용|보험되|예약|후기(?!_)|진료비|한약값|첩약|상담비|치료비|급여|비급여)/;
const TREAT=/(치료|한방치료|침치료|약침|추나|뜸치료|한약치료|교정치료|치료기간|치료방법|치료법)/;
const SOFT=/(고치는법|낫는법|낫게|완치)/;
const CHRONIC=/(만성|계속|지속|반복|오래|몇년|몇달|수년|매일|달고사|고질|난치)/;
const SEVERE=/(심한|심할|심해|극심|너무아|죽을|못견|못참|깨질|터질|토할|구토|응급)/;
const LOCAL=/(강남|강남역|서초|역삼|신논현|논현|교대|양재|삼성역|선릉|테헤란)/;
// 조합 생성물 냄새(컷이 아니라 표시용): ICHD-3 학술명 / 기계조합 꼬리
const SYNTH=/(개연|저빈도삽화|고빈도삽화|단기지속편측|가족반신마비|산발반신마비|뇌간조짐|망막편두통|경막천자후|경동맥내막|삼차자율신경|원발벼락|심리적요인|정서적요인|정신적요인|요인치료|방법정리|기초효과|분석사례|실천|정리방법|분석법)/;
function grade(raw){
 let s=norm(raw);
 if(/(임신|생리)(초기|중기|후기|말기)/.test(s))s=s.replace(/(임신|생리)(초기|중기|후기|말기)/g,'$1$2_');  // '후기'(리뷰) 오인 차단
 if(!AXIS.test(s))return null;
 if(JUNK.test(s)||OTHER.test(s))return null;
 const fail=FAIL.test(s);
 if(!fail&&(SELF.test(s)||DRUG.test(s)))return null;   // 양방실패 먼저 통과
 const h=[];
 if(CLINIC.test(s))h.push('clinic');
 if(DECIDE.test(s))h.push('decide');
 if(TREAT.test(s))h.push('treat');
 if(SOFT.test(s))h.push('soft');
 if(fail)h.push('fail');
 if(CHRONIC.test(s))h.push('chronic');
 if(SEVERE.test(s))h.push('severe');
 if(LOCAL.test(s))h.push('local');
 const H=new Set(h);
 if(!(H.has('clinic')||H.has('decide')||H.has('treat')||H.has('fail')||H.has('soft')))return null;
 let g;
 if(H.has('clinic')&&(H.has('decide')||H.has('fail')||H.has('chronic')||H.has('local')))g='S';
 else if(H.has('clinic')||H.has('decide'))g='A';
 else if(H.has('treat'))g='A';
 else g='B';                                            // 치료행위·양방실패 단독
 return {grade:g,sig:h,synth:SYNTH.test(s)};
}
return {grade,norm,RE:{AXIS,JUNK,OTHER,FAIL,SELF,DRUG,CLINIC,DECIDE,TREAT,SOFT,CHRONIC,SEVERE,LOCAL,SYNTH}};
})();
