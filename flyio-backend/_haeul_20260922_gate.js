const DIAG_ADJ = /(안진|온도자극|칼로릭|두부충동|두진|전정유발근전위|회전의자|동적자세|기립경사|발살바|심박변이|평형기능|전정기능검사|딕스|홀파이크|프렌젤|프렌첼)/;
