const LEARN_TAIL = /(위치|구조|역할|원리|의기능|기능$|차이|뜻|이란|란$|정의|영어|영문|해부|그림|사진|모형)/;

function judge(kw) {
  const s = String(kw).replace(/\s+/g, '').toLowerCase();
  if (s.length < 3) return { ok: 0, why: 'too_short' };
  for (const re of NOISE) if (re.test(s)) return { ok: 0, why: 'noise:' + re.source.slice(0, 14) };
  const proc = PROC.test(s);
  if (!proc && SELF.test(s)) return { ok: 0, why: 'self' };
  const b = I.bucket(s);
  // 해부어 + 학습 꼬리는 공식어 구제 대상에서 제외한다
  if (ANAT.test(s) && LEARN_TAIL.test(s)) return { ok: 0, why: 'anatomy_learn' };
  const official = AXIS_OFFICIAL.test(s);
  const diag = DIAG_ADJ.test(s);
  // 축 판정은 기존 판정기에 맡기되, 공식 어휘층·시술명은 축 밖으로 빠져도 살린다
  if (b.scope === 'out' && !proc && !official && !diag) return { ok: 0, why: 'offscope:' + b.b };
  if (b.scope === 'out' && !official && !proc && diag) {
    return { ok: 1, bucket: '7_진료범위밖_인접(원장확인)', visit: 1, proc: 0, sig: 'diagnostic' };
  }
  // 시술명 + 정보성 꼬리는 내원이 아니다
  const visit = (VISIT.test(s) && !(proc && PROC_INFO.test(s) && !/(병원|한의원|의원|클리닉|비용|보험|실비|가격)/.test(s)))
    || (proc && /(병원|한의원|의원|클리닉|비용|보험|실비|가격|추천|어디)/.test(s));
  // 공식 질환명이 축밖으로 판정됐으면 버킷을 축 안으로 되돌린다(질환명단독/정보탐색)
  if (b.scope === 'out' && official) {
    return { ok: 1, bucket: visit ? '2_내원A' : '4_질환명단독', visit: visit ? 1 : 0,
             proc: proc ? 1 : 0, sig: 'official' };
  }
  return { ok: 1, bucket: b.b, visit: visit ? 1 : 0, proc: proc ? 1 : 0, sig: b.sig || '' };
}
module.exports = { judge };
